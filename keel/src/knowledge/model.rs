//! Knowledge record model: types, provenance, validation, and JSON shape.
//!
//! Field names follow the roadmap schema (`source_path`, `source_hash`,
//! `commit_hash`) with aliases for the roadmap's example payload (`file`,
//! `symbol`, `commit`, `statement`), so both spellings parse. Parsing is
//! lenient; [`KnowledgeRecord::validate`] is strict and gates every store
//! write. Timestamps are decimal unix seconds in strings (matching the
//! `meta.last_indexed` convention) and are owned by the store, which stamps
//! them on write — caller-supplied values are replaced, never trusted.

use crate::error::{KeelError, Result};
use serde::{Deserialize, Deserializer, Serialize, Serializer};

/// Maximum record id length in bytes.
pub const MAX_ID_LEN: usize = 256;
/// Maximum title length in bytes.
pub const MAX_TITLE_LEN: usize = 512;
/// Maximum content length in bytes (long explanations allowed, unbounded blobs not).
pub const MAX_CONTENT_LEN: usize = 1_000_000;
/// Maximum evidence entries per record.
pub const MAX_EVIDENCE: usize = 256;
/// Maximum evidence path/symbol lengths in bytes.
pub const MAX_EVIDENCE_PATH_LEN: usize = 1024;
pub const MAX_EVIDENCE_SYMBOL_LEN: usize = 512;
/// Raw SHA-256 hex length (evidence hashes mirror `files.content_hash`).
pub const SOURCE_HASH_HEX_LEN: usize = 64;

/// The kind of claim a knowledge record makes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KnowledgeType {
    /// A structural fact about the code (deterministic or asserted).
    Fact,
    /// A human-authored architecture decision.
    Decision,
    /// An (often agent-generated) explanation of code behavior.
    Explanation,
    /// An inferred architectural pattern.
    Pattern,
    /// A known constraint or limitation.
    Constraint,
    /// Forward-compatible escape hatch for future types.
    Other(String),
}

impl KnowledgeType {
    /// Serialize to the string stored in `knowledge.type` and JSON `type`.
    pub fn as_db(&self) -> String {
        match self {
            KnowledgeType::Fact => "architecture_fact".to_string(),
            KnowledgeType::Decision => "decision".to_string(),
            KnowledgeType::Explanation => "explanation".to_string(),
            KnowledgeType::Pattern => "pattern".to_string(),
            KnowledgeType::Constraint => "constraint".to_string(),
            KnowledgeType::Other(s) => s.clone(),
        }
    }

    /// Parse from storage. Unknown values round-trip through `Other` so new
    /// writers never brick old readers.
    pub fn from_db(s: &str) -> KnowledgeType {
        match s {
            "architecture_fact" | "fact" => KnowledgeType::Fact,
            "decision" => KnowledgeType::Decision,
            "explanation" => KnowledgeType::Explanation,
            "pattern" => KnowledgeType::Pattern,
            "constraint" => KnowledgeType::Constraint,
            other => KnowledgeType::Other(other.to_string()),
        }
    }
}

/// Who produced a knowledge record. Provenance is enforced on write: a stored
/// [`KnowledgeOrigin::Human`] record rejects non-human overwrites.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KnowledgeOrigin {
    /// Authored or reviewed by a human.
    Human,
    /// Generated by a coding agent.
    Agent,
    /// Inferred by analysis (patterns, heuristics).
    Inferred,
    /// Derived deterministically from the index (structural relationships).
    Deterministic,
    /// Forward-compatible escape hatch for future origins.
    Other(String),
}

impl KnowledgeOrigin {
    /// Serialize to the string stored in `knowledge.origin` and JSON `origin`.
    pub fn as_db(&self) -> String {
        match self {
            KnowledgeOrigin::Human => "human".to_string(),
            KnowledgeOrigin::Agent => "agent_generated".to_string(),
            KnowledgeOrigin::Inferred => "inferred".to_string(),
            KnowledgeOrigin::Deterministic => "deterministic".to_string(),
            KnowledgeOrigin::Other(s) => s.clone(),
        }
    }

    /// Parse from storage. `"agent"` is accepted as an alias of the canonical
    /// `"agent_generated"`; unknown values round-trip through `Other`.
    pub fn from_db(s: &str) -> KnowledgeOrigin {
        match s {
            "human" => KnowledgeOrigin::Human,
            "agent_generated" | "agent" => KnowledgeOrigin::Agent,
            "inferred" => KnowledgeOrigin::Inferred,
            "deterministic" => KnowledgeOrigin::Deterministic,
            other => KnowledgeOrigin::Other(other.to_string()),
        }
    }

    /// Whether this origin counts as human for provenance protection.
    pub fn is_human(&self) -> bool {
        *self == KnowledgeOrigin::Human
    }
}

/// Freshness of a knowledge record against the current code.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KnowledgeStatus {
    /// Current evidence supports the claim.
    Supported,
    /// The claim has not been checked.
    Unverified,
    /// Supporting code has changed since the claim was verified.
    Stale,
    /// Current evidence conflicts with the claim.
    Contradicted,
}

impl KnowledgeStatus {
    /// Serialize to the string stored in `knowledge.status` and JSON `status`.
    pub fn as_db(&self) -> &'static str {
        match self {
            KnowledgeStatus::Supported => "supported",
            KnowledgeStatus::Unverified => "unverified",
            KnowledgeStatus::Stale => "stale",
            KnowledgeStatus::Contradicted => "contradicted",
        }
    }

    /// Parse from storage. Unknown values fall back to [`KnowledgeStatus::Unverified`]:
    /// an unreadable status must never present as supported.
    pub fn from_db(s: &str) -> KnowledgeStatus {
        match s {
            "supported" => KnowledgeStatus::Supported,
            "stale" => KnowledgeStatus::Stale,
            "contradicted" => KnowledgeStatus::Contradicted,
            _ => KnowledgeStatus::Unverified,
        }
    }
}

impl Serialize for KnowledgeType {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.as_db())
    }
}

impl<'de> Deserialize<'de> for KnowledgeType {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        String::deserialize(deserializer).map(|s| KnowledgeType::from_db(&s))
    }
}

impl Serialize for KnowledgeOrigin {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.as_db())
    }
}

impl<'de> Deserialize<'de> for KnowledgeOrigin {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        String::deserialize(deserializer).map(|s| KnowledgeOrigin::from_db(&s))
    }
}

impl Serialize for KnowledgeStatus {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        serializer.serialize_str(self.as_db())
    }
}

impl<'de> Deserialize<'de> for KnowledgeStatus {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        String::deserialize(deserializer).map(|s| KnowledgeStatus::from_db(&s))
    }
}

/// One source backing a knowledge record: a file, optionally a symbol inside
/// it, pinned to the file's content hash (and optionally a commit).
///
/// `symbol` stores the symbol *name*, not the `symbols` row id: row ids are
/// reassigned on every re-index, while names survive. `source_hash` mirrors
/// `files.content_hash` (raw lowercase SHA-256 hex) so invalidation can
/// compare directly; [`normalize_source_hash`] canonicalizes inputs.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct KnowledgeEvidence {
    /// Indexed file path, relative to the project root (as in `files.path`).
    #[serde(alias = "file")]
    pub source_path: String,
    /// Symbol name within the file, when the evidence is symbol-scoped.
    #[serde(default, skip_serializing_if = "Option::is_none", alias = "symbol_id")]
    pub symbol: Option<String>,
    /// File content hash the claim was verified against (raw SHA-256 hex).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_hash: Option<String>,
    /// Commit the claim was verified against, when version control is available.
    #[serde(default, skip_serializing_if = "Option::is_none", alias = "commit")]
    pub commit_hash: Option<String>,
}

/// A durable, source-linked knowledge record.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct KnowledgeRecord {
    /// Stable caller-chosen id, e.g. `auth.jwt.validation`.
    pub id: String,
    /// The kind of claim this record makes.
    #[serde(rename = "type")]
    pub record_type: KnowledgeType,
    /// Short human-readable title.
    #[serde(default)]
    pub title: String,
    /// The claim itself (roadmap example spells this `statement`).
    #[serde(alias = "statement")]
    pub content: String,
    /// Who produced this record.
    pub origin: KnowledgeOrigin,
    /// Freshness against the current code.
    pub status: KnowledgeStatus,
    /// Decimal unix seconds, stamped by the store on insert.
    #[serde(default)]
    pub created_at: String,
    /// Decimal unix seconds, stamped by the store on every write.
    #[serde(default)]
    pub updated_at: String,
    /// Source backing for the claim (may be empty for ungrounded claims,
    /// which then can never reach `supported` honestly).
    #[serde(default)]
    pub evidence: Vec<KnowledgeEvidence>,
}

impl KnowledgeRecord {
    /// Build a new unverified record with fresh timestamps and no evidence.
    pub fn new(
        id: impl Into<String>,
        record_type: KnowledgeType,
        title: impl Into<String>,
        content: impl Into<String>,
        origin: KnowledgeOrigin,
    ) -> Self {
        let now = now_timestamp();
        Self {
            id: id.into(),
            record_type,
            title: title.into(),
            content: content.into(),
            origin,
            status: KnowledgeStatus::Unverified,
            created_at: now.clone(),
            updated_at: now,
            evidence: Vec::new(),
        }
    }

    /// Validate every field; the store calls this before any write.
    pub fn validate(&self) -> Result<()> {
        validate_id(&self.id)?;
        if self.title.trim().is_empty() {
            return Err(validation("title must not be empty"));
        }
        if self.title.len() > MAX_TITLE_LEN {
            return Err(validation(format!(
                "title exceeds {MAX_TITLE_LEN} bytes"
            )));
        }
        if self.content.trim().is_empty() {
            return Err(validation("content must not be empty"));
        }
        if self.content.len() > MAX_CONTENT_LEN {
            return Err(validation(format!(
                "content exceeds {MAX_CONTENT_LEN} bytes"
            )));
        }
        if self.evidence.len() > MAX_EVIDENCE {
            return Err(validation(format!(
                "evidence exceeds {MAX_EVIDENCE} entries"
            )));
        }
        for (i, e) in self.evidence.iter().enumerate() {
            e.validate(i)?;
        }
        Ok(())
    }
}

impl KnowledgeEvidence {
    /// Validate one evidence entry (`index` names it in error messages).
    pub fn validate(&self, index: usize) -> Result<()> {
        let what = format!("evidence[{index}]");
        if self.source_path.trim().is_empty() {
            return Err(validation(format!("{what}: source_path must not be empty")));
        }
        if self.source_path != self.source_path.trim() {
            return Err(validation(format!(
                "{what}: source_path must not have surrounding whitespace"
            )));
        }
        if self.source_path.len() > MAX_EVIDENCE_PATH_LEN {
            return Err(validation(format!(
                "{what}: source_path exceeds {MAX_EVIDENCE_PATH_LEN} bytes"
            )));
        }
        if let Some(symbol) = &self.symbol {
            if symbol.trim().is_empty() {
                return Err(validation(format!("{what}: symbol must not be blank")));
            }
            if symbol != symbol.trim() {
                return Err(validation(format!(
                    "{what}: symbol must not have surrounding whitespace"
                )));
            }
            if symbol.len() > MAX_EVIDENCE_SYMBOL_LEN {
                return Err(validation(format!(
                    "{what}: symbol exceeds {MAX_EVIDENCE_SYMBOL_LEN} bytes"
                )));
            }
        }
        if let Some(hash) = &self.source_hash {
            normalize_source_hash(hash).map_err(|e| {
                validation(format!("{what}: invalid source_hash: {e}"))
            })?;
        }
        if let Some(commit) = &self.commit_hash {
            if commit.trim().is_empty() || commit.len() > 128 {
                return Err(validation(format!(
                    "{what}: commit_hash must be 1..=128 chars"
                )));
            }
            if commit.chars().any(char::is_whitespace) {
                return Err(validation(format!(
                    "{what}: commit_hash must not contain whitespace"
                )));
            }
        }
        Ok(())
    }
}

fn validation(message: impl Into<String>) -> KeelError {
    KeelError::KnowledgeValidation(message.into())
}

fn validate_id(id: &str) -> Result<()> {
    if id.trim().is_empty() {
        return Err(validation("id must not be empty"));
    }
    if id != id.trim() {
        return Err(validation("id must not have surrounding whitespace"));
    }
    if id.len() > MAX_ID_LEN {
        return Err(validation(format!("id exceeds {MAX_ID_LEN} bytes")));
    }
    if !id
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-' | '/' | ':'))
    {
        return Err(validation(
            "id may only contain ASCII letters, digits, and . _ - / :",
        ));
    }
    Ok(())
}

/// Canonicalize an evidence source hash for comparison with `files.content_hash`.
///
/// Accepts raw hex or a `sha256:`-prefixed digest in any case; returns raw
/// lowercase hex. Anything else is a validation error.
pub fn normalize_source_hash(raw: &str) -> std::result::Result<String, String> {
    let hex = raw
        .strip_prefix("sha256:")
        .or_else(|| raw.strip_prefix("SHA256:"))
        .unwrap_or(raw);
    if hex.len() != SOURCE_HASH_HEX_LEN {
        return Err(format!(
            "expected {SOURCE_HASH_HEX_LEN} hex chars, found {}",
            hex.len()
        ));
    }
    if !hex.bytes().all(|b| b.is_ascii_hexdigit()) {
        return Err("expected hex digits".to_string());
    }
    Ok(hex.to_ascii_lowercase())
}

/// Current time as decimal unix seconds (0 when the clock is unreadable).
pub fn now_timestamp() -> String {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    const ROADMAP_EXAMPLE: &str = r#"{
        "id": "auth.jwt.validation",
        "type": "architecture_fact",
        "statement": "JWT validation occurs in AuthMiddleware",
        "origin": "agent_generated",
        "status": "unverified",
        "evidence": [
            {
                "file": "src/auth/middleware.ts",
                "symbol": "validateToken",
                "commit": "abc123",
                "source_hash": "sha256:example"
            }
        ]
    }"#;

    fn valid_record() -> KnowledgeRecord {
        KnowledgeRecord {
            id: "auth.jwt.validation".to_string(),
            record_type: KnowledgeType::Fact,
            title: "JWT validation".to_string(),
            content: "JWT validation occurs in AuthMiddleware".to_string(),
            origin: KnowledgeOrigin::Agent,
            status: KnowledgeStatus::Unverified,
            created_at: "1700000000".to_string(),
            updated_at: "1700000000".to_string(),
            evidence: vec![KnowledgeEvidence {
                source_path: "src/auth/middleware.ts".to_string(),
                symbol: Some("validateToken".to_string()),
                source_hash: Some("a".repeat(64)),
                commit_hash: Some("abc123".to_string()),
            }],
        }
    }

    #[test]
    fn roadmap_example_payload_parses() {
        // The roadmap's example uses `statement`/`file`/`commit` spellings and
        // omits `title`: parsing is lenient, validation stays strict.
        let record: KnowledgeRecord = serde_json::from_str(ROADMAP_EXAMPLE).unwrap();
        assert_eq!(record.id, "auth.jwt.validation");
        assert_eq!(record.record_type, KnowledgeType::Fact);
        assert_eq!(record.content, "JWT validation occurs in AuthMiddleware");
        assert_eq!(record.origin, KnowledgeOrigin::Agent);
        assert_eq!(record.status, KnowledgeStatus::Unverified);
        assert_eq!(record.evidence.len(), 1);
        let e = &record.evidence[0];
        assert_eq!(e.source_path, "src/auth/middleware.ts");
        assert_eq!(e.symbol.as_deref(), Some("validateToken"));
        assert_eq!(e.commit_hash.as_deref(), Some("abc123"));
        // The placeholder hash parses (validation, not parsing, rejects it).
        assert_eq!(e.source_hash.as_deref(), Some("sha256:example"));
    }

    #[test]
    fn canonical_json_roundtrips() {
        let record = valid_record();
        let json = serde_json::to_string(&record).unwrap();
        let back: KnowledgeRecord = serde_json::from_str(&json).unwrap();
        assert_eq!(record, back);
        // Canonical spellings are schema-aligned, not alias spellings.
        let value: serde_json::Value = serde_json::from_str(&json).unwrap();
        assert_eq!(value["type"], "architecture_fact");
        assert_eq!(value["origin"], "agent_generated");
        assert_eq!(value["evidence"][0]["source_path"], "src/auth/middleware.ts");
        assert!(value.get("statement").is_none());
    }

    #[test]
    fn new_record_defaults_to_unverified_without_evidence() {
        let record = KnowledgeRecord::new(
            "x",
            KnowledgeType::Decision,
            "T",
            "C",
            KnowledgeOrigin::Human,
        );
        assert_eq!(record.status, KnowledgeStatus::Unverified);
        assert!(record.evidence.is_empty());
        assert!(!record.created_at.is_empty());
        record.validate().unwrap();
    }

    #[test]
    fn type_origin_status_db_roundtrips() {
        for (t, s) in [
            (KnowledgeType::Fact, "architecture_fact"),
            (KnowledgeType::Decision, "decision"),
            (KnowledgeType::Explanation, "explanation"),
            (KnowledgeType::Pattern, "pattern"),
            (KnowledgeType::Constraint, "constraint"),
        ] {
            assert_eq!(t.as_db(), s);
            assert_eq!(KnowledgeType::from_db(s), t);
        }
        assert_eq!(KnowledgeType::from_db("fact"), KnowledgeType::Fact);
        assert_eq!(
            KnowledgeType::from_db("brand_new"),
            KnowledgeType::Other("brand_new".to_string())
        );
        for (o, s) in [
            (KnowledgeOrigin::Human, "human"),
            (KnowledgeOrigin::Agent, "agent_generated"),
            (KnowledgeOrigin::Inferred, "inferred"),
            (KnowledgeOrigin::Deterministic, "deterministic"),
        ] {
            assert_eq!(o.as_db(), s);
            assert_eq!(KnowledgeOrigin::from_db(s), o);
        }
        assert_eq!(KnowledgeOrigin::from_db("agent"), KnowledgeOrigin::Agent);
        assert!(KnowledgeOrigin::Human.is_human());
        assert!(!KnowledgeOrigin::Agent.is_human());
        for (st, s) in [
            (KnowledgeStatus::Supported, "supported"),
            (KnowledgeStatus::Unverified, "unverified"),
            (KnowledgeStatus::Stale, "stale"),
            (KnowledgeStatus::Contradicted, "contradicted"),
        ] {
            assert_eq!(st.as_db(), s);
            assert_eq!(KnowledgeStatus::from_db(s), st);
        }
        // Unknown statuses must never read as supported.
        assert_eq!(
            KnowledgeStatus::from_db("bogus"),
            KnowledgeStatus::Unverified
        );
    }

    #[test]
    fn normalize_source_hash_accepts_prefixed_and_uppercase() {
        let lower = "a".repeat(64);
        assert_eq!(normalize_source_hash(&lower).unwrap(), lower);
        assert_eq!(
            normalize_source_hash(&format!("sha256:{lower}")).unwrap(),
            lower
        );
        let upper = "A".repeat(64);
        assert_eq!(normalize_source_hash(&upper).unwrap(), lower);
        assert!(normalize_source_hash("abc").is_err());
        assert!(normalize_source_hash(&"z".repeat(64)).is_err());
        assert!(normalize_source_hash("sha256:example").is_err());
    }

    #[test]
    fn validation_rejects_bad_ids() {
        for bad in ["", "   ", " has-space ", "semi;colon", "quote\"q", "back\\slash"] {
            let mut r = valid_record();
            r.id = bad.to_string();
            assert!(r.validate().is_err(), "id {bad:?} must be rejected");
        }
        let mut r = valid_record();
        r.id = "x".repeat(MAX_ID_LEN + 1);
        assert!(r.validate().is_err());
        for ok in ["a", "auth.jwt.validation", "ADR-001", "team/scope:rule_2"] {
            let mut r = valid_record();
            r.id = ok.to_string();
            assert!(r.validate().is_ok(), "id {ok:?} must be accepted");
        }
    }

    #[test]
    fn validation_rejects_empty_title_content_and_bad_evidence() {
        let mut r = valid_record();
        r.title = "  ".to_string();
        assert!(r.validate().is_err());
        r = valid_record();
        r.content = String::new();
        assert!(r.validate().is_err());

        r = valid_record();
        r.evidence[0].source_path = String::new();
        assert!(r.validate().is_err());
        r = valid_record();
        r.evidence[0].source_path = " x.py ".to_string();
        assert!(r.validate().is_err());
        r = valid_record();
        r.evidence[0].symbol = Some("  ".to_string());
        assert!(r.validate().is_err());
        r = valid_record();
        r.evidence[0].source_hash = Some("not-a-hash".to_string());
        assert!(r.validate().is_err());
        r = valid_record();
        r.evidence[0].commit_hash = Some("has space".to_string());
        assert!(r.validate().is_err());

        // File-level evidence (no symbol/hash/commit) is valid.
        r = valid_record();
        r.evidence[0].symbol = None;
        r.evidence[0].source_hash = None;
        r.evidence[0].commit_hash = None;
        assert!(r.validate().is_ok());
        // So is a record with no evidence at all (never honestly `supported`).
        r.evidence.clear();
        assert!(r.validate().is_ok());
    }
}
